#!/usr/bin/env python3
"""Write the MastersOS wordmark as outlines: "Masters" in Plus Jakarta Sans SemiBold and "OS" in Medium at 55 % opacity,
letter spacing -0.025 em (design 2026-11-04 visual identity §3). Devices never need the font.

Usage: wordmark.py <font [wght] ttf> <out.svg> [fill colour, default #FFFFFF]
"""
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

TRACKING = -0.025  # em
PARTS = (("Masters", 600, 1.0), ("OS", 500, 0.55))


def outlines(font_path, text, weight, x, upm_out):
    font = instantiateVariableFont(TTFont(font_path), {"wght": weight})
    upm = font["head"].unitsPerEm
    scale = upm_out / upm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    paths = []
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        # font units are y-up; flip into SVG's y-down with the baseline at upm_out
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, upm_out)))
        paths.append(pen.getCommands())
        x += hmtx[name][0] * scale + TRACKING * upm_out
    asc = font["hhea"].ascender * scale
    desc = -font["hhea"].descender * scale
    return " ".join(paths), x, asc, desc


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    font_path, out = sys.argv[1], sys.argv[2]
    fill = sys.argv[3] if len(sys.argv) == 4 else "#FFFFFF"
    em = 100
    x = 0.0
    groups = []
    top = bottom = 0.0
    for text, weight, opacity in PARTS:
        d, x, asc, desc = outlines(font_path, text, weight, x, em)
        groups.append(f'<path d="{d}" fill-opacity="{opacity}"/>')
        top, bottom = max(top, asc), max(bottom, desc)
    width = x - TRACKING * em
    y0 = em - top
    height = top + bottom
    svg = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!-- MastersOS wordmark, generated by image/brand/wordmark.py from Plus Jakarta Sans (OFL); do not edit. -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 {y0:.2f} {width:.2f} {height:.2f}" '
        f'width="{width * 0.4:.0f}" height="{height * 0.4:.0f}">\n'
        f'  <g fill="{fill}">{"".join(groups)}</g>\n</svg>\n'
    )
    with open(out, "w", encoding="utf-8") as f:
        f.write(svg)


if __name__ == "__main__":
    main()
