//! The shared vector files of protocol §8, loaded by their protocol names, and the wire vectors.
//! The server team copies `testdata/{digest,heartbeat,escrow,kit,wire}-vectors.json` byte for
//! byte into its tests. The checks live in `mastersos_bundle::vectors`.

use mastersos_bundle::vectors;

fn testdata(name: &str) -> String {
    let path = format!("{}/testdata/{name}", env!("CARGO_MANIFEST_DIR"));
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("reading {path}: {e}"))
}

#[test]
fn digest_vectors_match() {
    assert!(vectors::check_digest_vectors(&testdata("digest-vectors.json")) >= 5);
}

/// Generated by `heartbeat::tests::regenerate_heartbeat_vectors` (`--ignored`).
#[test]
fn heartbeat_vectors_match() {
    assert!(vectors::check_heartbeat_vectors(&testdata("heartbeat-vectors.json")) >= 3);
}

/// Protocol §8: the server runs exactly these four files. Every vector of each is parsed and
/// recomputed or verified.
#[test]
fn shared_vectors_are_the_protocol_files() {
    assert!(vectors::check_digest_vectors(&testdata("digest-vectors.json")) >= 5);
    assert!(vectors::check_heartbeat_vectors(&testdata("heartbeat-vectors.json")) >= 3);
    assert_eq!(
        vectors::check_escrow_vectors(&testdata("escrow-vectors.json")),
        1
    );
    assert_eq!(vectors::check_kit_vectors(&testdata("kit-vectors.json")), 3);
}

/// `testdata/wire-vectors.json` equals what `vectors::wire_vectors` computes now, byte for byte,
/// and every entry checks out (valid ones read back and verify, invalid ones are refused).
/// `MASTERSOS_REGEN_VECTORS=1` rewrites the file instead; on a mismatch the expected text is
/// printed as numbered `WIREVEC|` lines.
#[test]
fn wire_vectors_are_current() {
    let path = format!("{}/testdata/wire-vectors.json", env!("CARGO_MANIFEST_DIR"));
    if vectors::regen() {
        std::fs::write(&path, vectors::file_text(&vectors::wire_vectors())).unwrap();
        return;
    }
    // A missing file reads as empty, so the expected text is still printed.
    vectors::check_wire_vectors(&std::fs::read_to_string(&path).unwrap_or_default());
}
