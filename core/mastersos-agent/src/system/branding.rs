    /// Both images by their own sha256: the icon goes to `logo_icon` (the quick settings row),
    /// the logo to `logo` and the GDM snippet; a stale `logo.webp` from the earlier agent goes.
    #[test]
    fn logo_and_icon_fetched_by_sha() {
        let root = tmp_root();
        let p = paths(root.path());
        let d = domains();
        let dir = p.public_dir.join("branding");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("logo.webp"), b"OLD").unwrap();
        let (logo, icon) = (b"LOGO-PNG".as_slice(), b"ICON-PNG".as_slice());
        let (lh, ih) = (sha256_hex(logo), sha256_hex(icon));
        let want = Want {
            name: Some(NAME),
            domains: &d,
            logo_sha256: Some(&lh),
            icon_sha256: Some(&ih),
            locale_managed: false,
        };
        let f = Fake::serving(&[logo, icon]);
        let r = FakeRunner::new();
        let out = go(&p, &want, Phase::Full, &f, &r, &mut SysState::default());
        assert_eq!(out, vec![ok(ITEM)]);
        assert_eq!(
            f.calls.borrow().as_slice(),
            [
                format!("https://mdm.example/api/device/v1/logos/{lh}.png"),
                format!("https://mdm.example/api/device/v1/logos/{ih}.png"),
            ]
        );
        assert_eq!(std::fs::read(dir.join("logo.png")).unwrap(), logo);
        assert_eq!(std::fs::read(dir.join("logo-icon.png")).unwrap(), icon);
        assert_eq!(mode(&dir.join("logo-icon.png")), 0o644);
        assert!(!dir.join("logo.webp").exists());
        let j = json(&p);
        assert_eq!(j["logo"], dir.join("logo.png").to_str().unwrap());
        assert_eq!(j["logo_icon"], dir.join("logo-icon.png").to_str().unwrap());
        let s = snippet(&p).unwrap();
        assert!(
            s.contains(&format!("logo='{}'", dir.join("logo.png").display())),
            "{s}"
        );
        // Both cached: nothing downloaded again.
        go(&p, &want, Phase::Full, &f, &r, &mut SysState::default());
        assert_eq!(f.calls.borrow().len(), 2);
        // A new icon: only the icon is fetched; a missing one leaves the logo in use.
        let ih2 = sha256_hex(b"NEW-ICON");
        let want2 = Want {
            icon_sha256: Some(&ih2),
            ..want
        };
        let out = go(&p, &want2, Phase::Full, &f, &r, &mut SysState::default());
        assert!(!out[0].ok);
        assert_eq!(f.calls.borrow().len(), 3);
        assert!(f.calls.borrow()[2].contains(&ih2));
        assert!(!dir.join("logo-icon.png").exists());
        let j = json(&p);
        assert_eq!(j["logo_icon"], serde_json::Value::Null);
        assert_eq!(j["logo"], dir.join("logo.png").to_str().unwrap());
        // The icon goes from the settings: its file goes too.
        let want3 = Want {
            icon_sha256: None,
            ..want
        };
        go(&p, &want3, Phase::Full, &f, &r, &mut SysState::default());
        assert!(!dir.join("logo-icon.png").exists());
        assert!(dir.join("logo.png").exists());
        // Unmanaged: everything goes.
        let none = Want { name: None, ..want };
        go(&p, &none, Phase::Full, &f, &r, &mut SysState::default());
        assert!(!dir.join("logo.png").exists());
    }

