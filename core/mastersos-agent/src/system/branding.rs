    #[test]
    fn dconf_update_retried_until_success() {
        let root = tmp_root();
        let p = paths(root.path());
        let d = domains();
        let hash = sha256_hex(b"LOGO");
        let mut sys = SysState::default();
        let r = FakeRunner::new();
        r.respond("dconf update", Output::fail(1, "boom"));
        let out = go(
            &p,
            &named(&d, Some(&hash)),
            Phase::Full,
            &Fake::bytes(b"LOGO"),
            &r,
            &mut sys,
        );
        assert!(!out[0].ok);
        assert!(sys.branding_dconf_pending);
        // Unchanged content, but the update still has to succeed.
        let r = FakeRunner::new();
        let out = go(
            &p,
            &named(&d, Some(&hash)),
            Phase::Full,
            &Fake::bytes(b"LOGO"),
            &r,
            &mut sys,
        );
        assert_eq!(out, vec![ok(ITEM)]);
        assert_eq!(r.calls(), vec!["dconf update"]);
        assert!(!sys.branding_dconf_pending);
        // And nothing more once it did.
        let r = FakeRunner::new();
        go(
            &p,
            &named(&d, Some(&hash)),
            Phase::Full,
            &Fake::bytes(b"LOGO"),
            &r,
            &mut sys,
        );
        assert!(r.calls().is_empty());
    }

