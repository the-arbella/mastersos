pub const ITEM: &str = "branding";
/// Directory under the public dir.
pub const DIR: &str = "branding";
pub const JSON_FILE: &str = "branding.json";
pub const LOGO_FILE: &str = "logo.png";
pub const ICON_FILE: &str = "logo-icon.png";
/// What the agent before the two PNGs cached; removed on sight.
const LEGACY_LOGO_FILE: &str = "logo.webp";
/// The GDM dconf snippet this step owns.
pub const GDM_FILE: &str = "80-mastersos-branding";
/// The logo download limits (the server keeps each PNG at most 128 KiB).
pub const MAX_LOGO_BYTES: usize = 128 * 1024;
pub const LOGO_TIMEOUT: Duration = Duration::from_secs(20);

const HEADER: &str =
    "# Generated by mastersos-agent: the school's branding on the login screen; do not edit.\n";

pub fn step() -> Step {
    Step {
        name: "branding",
        fast: true,
        run,
        without_bundle: Some(run_seed),
    }
}

/// Where the logo comes from; tests inject a fake.
pub trait LogoFetcher {
    fn fetch(&self, url: &str) -> Result<Vec<u8>>;
}

struct HttpFetcher;

impl LogoFetcher for HttpFetcher {
    fn fetch(&self, url: &str) -> Result<Vec<u8>> {
        let url = url.to_string();
        let fut = async move {
            let client = crate::fetch::http_client(crate::fetch::HttpOpts {
                connect: Duration::from_secs(10),
                read: Some(Duration::from_secs(10)),
                total: Some(LOGO_TIMEOUT),
            });
            let mut resp = client.get(&url).send().await?.error_for_status()?;
            if resp
                .content_length()
                .is_some_and(|n| n > MAX_LOGO_BYTES as u64)
            {
                bail!("the logo is larger than 128 KiB");
            }
            let mut buf = Vec::new();
            while let Some(chunk) = resp.chunk().await? {
                buf.extend_from_slice(&chunk);
                if buf.len() > MAX_LOGO_BYTES {
                    bail!("the logo is larger than 128 KiB");
                }
            }
            Ok(buf)
        };
        match tokio::runtime::Handle::try_current() {
            Ok(h) => h.block_on(fut),
            Err(_) => tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()
                .context("building a tokio runtime")?
                .block_on(fut),
        }
    }
}

#[derive(Serialize)]
struct Branding<'a> {
    school_name: &'a str,
    logo: Option<String>,
    logo_icon: Option<String>,
    domains: &'a [String],
    locale_managed: bool,
}

/// What one round wants.
struct Want<'a> {
    name: Option<&'a str>,
    domains: &'a [String],
    /// `[school] logo_sha256`; `None` means no sign-in logo (and no cache).
    logo_sha256: Option<&'a str>,
    /// `[school] logo_icon_sha256`; `None` means no quick menu icon (and no cache).
    icon_sha256: Option<&'a str>,
    /// `[school] locale` is set.
    locale_managed: bool,
}

fn run(ctx: &ApplyContext, env: &mut Env) -> Vec<ItemResult> {
    let name = ctx
        .school
        .name
        .as_deref()
        .or(ctx.seed.school_name.as_deref());
    let want = Want {
        name,
        domains: &ctx.school.allowed_domains,
        logo_sha256: ctx.school.logo_sha256.as_deref(),
        icon_sha256: ctx.school.logo_icon_sha256.as_deref(),
        locale_managed: ctx.school.locale.is_some(),
    };
    apply(&want, &ctx.seed.server_url, ctx.phase, env, &HttpFetcher)
}

/// Before the first settings: only the seed's school name.
fn run_seed(seed: &Seed, env: &mut Env) -> Vec<ItemResult> {
    let want = Want {
        name: seed.school_name.as_deref(),
        domains: &[],
        logo_sha256: None,
        icon_sha256: None,
        locale_managed: false,
    };
    apply(&want, &seed.server_url, Phase::Boot, env, &HttpFetcher)
}

fn apply(
    want: &Want,
    server_url: &str,
    phase: Phase,
    env: &mut Env,
    fetcher: &dyn LogoFetcher,
) -> Vec<ItemResult> {
    let mut problems = Vec::new();
    let name = want.name.map(str::trim).filter(|n| !n.is_empty());
    let logo_path = match sync_files(want, name, server_url, phase, env, fetcher, &mut problems) {
        Ok(p) => p,
        Err(e) => {
            problems.push(format!("{e:#}"));
            None
        }
    };
    let snippet = logo_path.as_deref().map(render_snippet);
    match sync_snippet(&env.paths.root, snippet.as_deref()) {
        Ok(changed) => env.sys.branding_dconf_pending |= changed,
        Err(e) => problems.push(format!("the GDM snippet: {e:#}")),
    }
    if env.sys.branding_dconf_pending || env.sys.load_failed {
        match run_ok(env.runner, Cmd::new("dconf", &["update"])) {
            Ok(_) => env.sys.branding_dconf_pending = false,
            Err(e) => problems.push(format!("dconf update: {e:#}")),
        }
    }
    vec![if problems.is_empty() {
        ok(ITEM)
    } else {
        failed(ITEM, problems.join("; "))
    }]
}

/// Writes or removes `branding.json` and the two cached images; returns the sign-in logo's
/// absolute path when it is in use.
fn sync_files(
    want: &Want,
    name: Option<&str>,
    server_url: &str,
    phase: Phase,
    env: &Env,
    fetcher: &dyn LogoFetcher,
    problems: &mut Vec<String>,
) -> Result<Option<String>> {
    let public = super::public_dir(env.paths)?;
    let Some(name) = name.or(want.locale_managed.then_some("")) else {
        // Nothing to show: take back what an earlier round wrote.
        if let Some(dir) = safefs::open_child_dir(&public, DIR)? {
            for f in [JSON_FILE, LOGO_FILE, ICON_FILE, LEGACY_LOGO_FILE] {
                safefs::remove_at(&dir, f)?;
            }
        }
        return Ok(None);
    };
    let dir = safefs::open_dir_at(&public, Path::new(DIR), true)?;
    safefs::set_mode(&dir, 0o755)?;
    safefs::remove_at(&dir, LEGACY_LOGO_FILE)?;
    let image = Image {
        dir: &dir,
        server_url,
        phase,
        fetcher,
    };
    let path = |used: bool, file: &str| {
        used.then(|| {
            env.paths
                .public_dir
                .join(DIR)
                .join(file)
                .to_string_lossy()
                .into_owned()
        })
    };
    let logo = path(
        image.sync(LOGO_FILE, want.logo_sha256, problems)?,
        LOGO_FILE,
    );
    let icon = path(
        image.sync(ICON_FILE, want.icon_sha256, problems)?,
        ICON_FILE,
    );
    let json = serde_json::to_vec_pretty(&Branding {
        school_name: name,
        logo: logo.clone(),
        logo_icon: icon,
        domains: want.domains,
        locale_managed: want.locale_managed,
    })?;
    safefs::write_at(&dir, JSON_FILE, &json, 0o644).context("writing branding.json")?;
    Ok(logo)
}

/// Where one round keeps and fetches the images.
struct Image<'a> {
    dir: &'a std::os::fd::OwnedFd,
    server_url: &'a str,
    phase: Phase,
    fetcher: &'a dyn LogoFetcher,
}

impl Image<'_> {
    /// Makes `file` hold the image whose SHA-256 is `hash` (or removes it for `None`); returns
    /// whether it is there and matches. A cached file that matches is kept without a download;
    /// at boot nothing is downloaded.
    fn sync(&self, file: &str, hash: Option<&str>, problems: &mut Vec<String>) -> Result<bool> {
        let Some(hash) = hash else {
            safefs::remove_at(self.dir, file)?;
            return Ok(false);
        };
        let cached = safefs::read_at(self.dir, file)?;
        if cached.as_deref().is_some_and(|b| sha256_hex(b) == hash) {
            return Ok(true);
        }
        if self.phase == Phase::Boot {
            return Ok(false);
        }
        // The server's lint keeps the value well formed; never build a URL from anything else.
        if !(hash.len() == 64 && hash.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))) {
            problems.push(format!(
                "{file}: the settings' sha256 is malformed; not used"
            ));
            safefs::remove_at(self.dir, file)?;
            return Ok(false);
        }
        let url = format!("{}/logos/{hash}.png", self.server_url.trim_end_matches('/'));
        match self.fetcher.fetch(&url) {
            Ok(b) if sha256_hex(&b) == hash => {
                safefs::write_at(self.dir, file, &b, 0o644)
                    .with_context(|| format!("writing the cached {file}"))?;
                Ok(true)
            }
            Ok(_) => {
                problems.push(format!(
                    "the logo from {url} does not match the settings' sha256; not used"
                ));
                safefs::remove_at(self.dir, file)?;
                Ok(false)
            }
            Err(e) => {
                problems.push(format!("downloading {url} failed: {e:#}"));
                safefs::remove_at(self.dir, file)?;
                Ok(false)
            }
        }
    }
}

/// The dconf keyfile with the logo key.
fn render_snippet(logo: &str) -> String {
    format!("{HEADER}[org/gnome/login-screen]\nlogo={}\n", gv_text(logo))
}

/// Writes (0644) or removes the snippet; returns whether it changed.
fn sync_snippet(root: &Path, want: Option<&str>) -> Result<bool> {
    match want {
        Some(text) => {
            let dir = safefs::open_dir(root, Path::new(GDM_DCONF_DIR), true)?;
            safefs::write_at(&dir, GDM_FILE, text.as_bytes(), 0o644)
                .with_context(|| format!("writing /{GDM_DCONF_DIR}/{GDM_FILE}"))
        }
        None => {
            let dir = match safefs::open_dir(root, Path::new(GDM_DCONF_DIR), false) {
                Ok(d) => d,
                Err(e) if is_not_found(&e) => return Ok(false),
                Err(e) => return Err(e),
            };
            if safefs::read_at(&dir, GDM_FILE)?.is_none() {
                return Ok(false);
            }
            safefs::remove_at(&dir, GDM_FILE)
                .with_context(|| format!("removing /{GDM_DCONF_DIR}/{GDM_FILE}"))?;
            Ok(true)
        }
    }
}

