//! School name, logo and login-screen data for the Devices (design 2026-10-30 §12).
//!
//! The `branding` step (fast, after `lock` and `login`) writes, under `<public_dir>/branding`
//! (0755, readable by the greeter and by user sessions; nothing secret):
//! - `branding.json`: `{"school_name", "logo", "logo_icon", "domains", "locale_managed"}` for the
//!   login-screen extension and the quick settings (`logo_icon` is the quick settings row's icon).
//!   `school_name` is `[school] name`, else the seed's `school_name` (a format-1 bundle has no
//!   `name`, so the seed is the normal source there); with neither nothing is written at all (an
//!   unmanaged Device or an old seed shows nothing), unless the settings set `locale`: the login
//!   screen must learn that, so the file is written with an empty name, which shows nothing.
//!   `locale_managed` says the signed settings set `locale`: the login screen then neither asks for
//!   a language nor offers to change it. No settings yet: false, and the file may not exist;
//! - `logo.png` and `logo-icon.png`: the sign-in logo (96 px high) and the quick menu icon
//!   (40 x 40), each used only when its SHA-256 equals `[school] logo_sha256` /
//!   `logo_icon_sha256`. Each is downloaded from `<seed.server_url>/logos/<sha256>.png` (128 KiB,
//!   20 s) outside `Phase::Boot`, unless the cached file already matches; a download that does not
//!   match is dropped (`null` in `branding.json`) and retried next round. The `logo.webp` an
//!   earlier agent cached is removed;
//! - the GDM dconf snippet `80-mastersos-branding` (`logo` key only: the login-screen extension shows
//!   the name and domains from `branding.json`, so there is no banner fallback). The lock banner
//!   `90-mastersos-lock` is a separate snippet.
//!
//! Report item: `branding`.

