/// 回报项的名字。
pub const ITEM: &str = "admins";

/// sudoers 的 drop-in 目录（相对系统根）、我们的文件与检查用的临时文件。
pub const SUDOERS_DIR: &str = "etc/sudoers.d";
pub const SUDOERS_FILE: &str = "mastersos-admins";
pub const SUDOERS_CHECK: &str = ".mastersos-admins.check";

/// polkit 规则目录（相对系统根）与我们的文件。
pub const POLKIT_DIR: &str = "etc/polkit-1/rules.d";
pub const POLKIT_FILE: &str = "49-mastersos-admins.rules";

/// 本机管理员组（镜像的 sysusers 建，`mkosi.finalize`）。
pub const LOCAL_ADMIN_GROUP: &str = "mastersos-localadmin";
/// 发行版的管理员组（GNOME 设置的「管理员」开关加的是 `sudo`；`/etc/sudoers` 还认 `%admin`）。
pub const SUDO_GROUP: &str = "sudo";
pub const ADMIN_GROUPS: &[&str] = &[SUDO_GROUP, "admin"];
/// GNOME 设置建「管理员」账号时 accountsservice 另外加的组（不是 root，但不该留给本机用户，复审 F4）。
pub const EXTRA_ADMIN_GROUPS: &[&str] = &["adm", "lpadmin"];
/// Ubuntu 让 `sudo`、`admin` 当 polkit 管理员的规则文件（`/usr/share/polkit-1/rules.d/`）。
pub const UBUNTU_ADMIN_RULE: &str = "49-ubuntu-admin.rules";
/// 访客账号（不是本机用户，永远不是管理员）。
const GUEST: &str = super::login::GUEST_USER;

/// 本机用户的 uid 范围：`[1000, 60000)`（与 `pam-check` 的系统账号界线相同）。
const HUMAN_UID_MIN: u32 = 1000;
const HUMAN_UID_END: u32 = 60000;

pub fn step() -> Step {
    Step {
        name: "admins",
        fast: true,
        run,
        without_bundle: Some(run_seed),
    }
}

/// 转小写、去重（按字典序）、只留过了 [`checks::admin_user`] 的；第二个返回值是被跳过的原值。
pub fn normalize_admins(admins: &[String]) -> (Vec<String>, Vec<String>) {
    let mut good = BTreeSet::new();
    let mut skipped = Vec::new();
    for a in admins {
        let l = a.to_ascii_lowercase();
        if checks::admin_user(&l).is_ok() {
            good.insert(l);
        } else {
            skipped.push(a.clone());
        }
    }
    (good.into_iter().collect(), skipped)
}

/// 每个账号一行 `"<name>" ALL=(ALL:ALL) ALL`（加引号：名字里的 `@` `.` 不必转义）；`local_admin` 时再加本机
/// 管理员组一行；`it_admin` 时再加 `itadmin ALL=(ALL:ALL) ALL`。都空返回空串（文件删除）。`admins` 只接受
/// [`normalize_admins`] 的第一个返回值。
pub fn render_sudoers(admins: &[String], local_admin: bool, it_admin: bool) -> String {
    if admins.is_empty() && !local_admin && !it_admin {
        return String::new();
    }
    let mut s =
        String::from("# Generated by mastersos-agent from the settings bundle; do not edit.\n");
    for a in admins {
        s.push_str(&format!("\"{a}\" ALL=(ALL:ALL) ALL\n"));
    }
    if it_admin {
        s.push_str(&it_sudoers_line());
    }
    if local_admin {
        s.push_str(&format!("%{LOCAL_ADMIN_GROUP} ALL=(ALL:ALL) ALL\n"));
    }
    s
}

/// `polkit.addAdminRule(function(action, subject) { return [...]; });`，列表是 JSON（名字经 `serde_json` 转义），
/// 每个账号一项 `unix-user:<name>`，`it_admin` 时加 `unix-user:itadmin`，`local_admin` 时加
/// `unix-group:mastersos-localadmin`。都空返回空串。
pub fn render_polkit(admins: &[String], local_admin: bool, it_admin: bool) -> String {
    if admins.is_empty() && !local_admin && !it_admin {
        return String::new();
    }
    let mut ids: Vec<String> = admins.iter().map(|a| format!("unix-user:{a}")).collect();
    if it_admin {
        ids.push(format!("unix-user:{IT_ACCOUNT_USER}"));
    }
    if local_admin {
        ids.push(format!("unix-group:{LOCAL_ADMIN_GROUP}"));
    }
    // Vec<String> 的序列化不会失败；万一失败就给空列表（polkit 照常问下一个规则）。
    let list = serde_json::to_string(&ids).unwrap_or_else(|_| "[]".into());
    format!(
        "// Generated by mastersos-agent from the settings bundle; do not edit.\n\
         polkit.addAdminRule(function(action, subject) {{ return {list}; }});\n"
    )
}

/// `/etc/passwd` 里的本机用户：uid 在 `[1000, 60000)`、不是 `guest`、名字不含 `@`（SSO 账号由 authd 经 NSS 给，
/// 本来就不在这个文件里；含 `@` 的也不算）。按文件里的顺序。
pub fn local_humans(passwd: &str) -> Vec<String> {
    let mut out = Vec::new();
    for line in passwd.lines() {
        let f: Vec<&str> = line.split(':').collect();
        if f.len() < 7 {
            continue;
        }
        let name = f[0];
        let Ok(uid) = f[2].parse::<u32>() else {
            continue;
        };
        if !portable_name(name)
            || name == GUEST
            || name.contains('@')
            || name.starts_with(['+', '-'])
            || !(HUMAN_UID_MIN..HUMAN_UID_END).contains(&uid)
        {
            continue;
        }
        if !out.iter().any(|n| n == name) {
            out.push(name.to_string());
        }
    }
    out
}

/// shadow-utils 的可移植用户名：`[a-z_][a-z0-9_.-]*\$?`，最多 32 字节（复审 F7：`gpasswd -M` 的列表用逗号连接，
/// 名字里不能有逗号、空白之类）。
fn portable_name(n: &str) -> bool {
    let b = n.as_bytes();
    let body = b.strip_suffix(b"$").unwrap_or(b);
    !body.is_empty()
        && n.len() <= 32
        && (body[0].is_ascii_lowercase() || body[0] == b'_')
        && body.iter().all(|&c| {
            c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, b'_' | b'.' | b'-')
        })
}

/// `/etc/group` 里组 `name` 的成员；没有这个组为 `None`。
fn group_members(group: &str, name: &str) -> Option<Vec<String>> {
    group.lines().find_map(|line| {
        let f: Vec<&str> = line.split(':').collect();
        (f.len() == 4 && f[0] == name).then(|| {
            f[3].split(',')
                .filter(|m| !m.is_empty())
                .map(str::to_string)
                .collect()
        })
    })
}

fn run(ctx: &ApplyContext, env: &mut Env) -> Vec<ItemResult> {
    let local_admin = ctx.config.local_users_admin;
    let (admins, skipped) = normalize_admins(&ctx.school.admin_users);
    let mut problems = Vec::new();
    if !skipped.is_empty() {
        problems.push(format!(
            "skipped {} invalid administrator account(s) (must look like name@school.ac.th)",
            skipped.len()
        ));
    }
    let it_admin = it_admin(env, ctx.config.it_account.as_ref());
    let root = env.paths.root.clone();
    problems.extend(apply_files(env, &root, &admins, local_admin, it_admin));
    problems.extend(apply_groups(env, &root, local_admin));
    report(problems)
}

/// Before the first bundle: only sudoers and polkit, for the seed's IT account; no group is touched (who is in them is
/// the bundle's `local_users_admin` to decide).
fn run_seed(seed: &Seed, env: &mut Env) -> Vec<ItemResult> {
    // A bundle was applied here before (or that is unknown this round): its admin files stay as they are, so the
    // install-time seed cannot give a removed IT account its sudo back.
    if super::it_account::seed_gated(env.sys) {
        return vec![ok(ITEM)];
    }
    let it_admin = it_admin(env, seed.it_account.as_ref());
    let root = env.paths.root.clone();
    report(apply_files(env, &root, &[], false, it_admin))
}

/// `itadmin` is an administrator when the settings keep it and the account is the one the agent created. In a round
/// whose state could not be read ownership is unknown: the installed sudoers file's answer is kept for that round.
fn it_admin(env: &Env, it: Option<&ItAccount>) -> bool {
    if super::it_account::wanted(it).is_none() {
        return false;
    }
    if env.sys.load_failed {
        return installed_sudoers(&env.paths.root)
            .is_some_and(|t| t.lines().any(|l| l == it_sudoers_line().trim_end()));
    }
    super::it_account::owned(env)
}

fn it_sudoers_line() -> String {
    format!("{IT_ACCOUNT_USER} ALL=(ALL:ALL) ALL\n")
}

fn installed_sudoers(root: &Path) -> Option<String> {
    let dir = safefs::open_dir(root, Path::new(SUDOERS_DIR), false).ok()?;
    let b = safefs::read_at(&dir, SUDOERS_FILE).ok()??;
    String::from_utf8(b).ok()
}

fn apply_files(
    env: &Env,
    root: &Path,
    admins: &[String],
    local_admin: bool,
    it_admin: bool,
) -> Vec<String> {
    let mut problems = Vec::new();
    if let Err(e) = apply_sudoers(env, root, &render_sudoers(admins, local_admin, it_admin)) {
        problems.push(format!("sudoers: {e:#}"));
    }
    if let Err(e) = apply_polkit(root, &render_polkit(admins, local_admin, it_admin)) {
        problems.push(format!("polkit: {e:#}"));
    }
    problems
}

fn report(problems: Vec<String>) -> Vec<ItemResult> {
    if problems.is_empty() {
        vec![ok(ITEM)]
    } else {
        vec![failed(ITEM, problems.join("; "))]
    }
}

/// 写 sudoers：空 → 删掉（连同残留的检查文件）；否则检查文件 → `visudo -cf` → `renameat` 换上。
fn apply_sudoers(env: &Env, root: &Path, text: &str) -> Result<()> {
    let dir = match safefs::open_dir(root, Path::new(SUDOERS_DIR), !text.is_empty()) {
        Ok(d) => d,
        Err(e) if text.is_empty() && is_not_found(&e) => return Ok(()),
        Err(e) => return Err(e).with_context(|| format!("open /{SUDOERS_DIR}")),
    };
    safefs::remove_at(&dir, SUDOERS_CHECK).context("delete the leftover check file")?;
    if text.is_empty() {
        return safefs::remove_at(&dir, SUDOERS_FILE);
    }
    safefs::write_at(&dir, SUDOERS_CHECK, text.as_bytes(), 0o440)
        .with_context(|| format!("write /{SUDOERS_DIR}/{SUDOERS_CHECK}"))?;
    let check = root.join(SUDOERS_DIR).join(SUDOERS_CHECK);
    let out = env
        .runner
        .run(&Cmd::new("visudo", &["-cf", &check.to_string_lossy()]));
    let passed = match &out {
        Ok(o) if o.code == 0 => true,
        Ok(o) => {
            // stderr 里可能有名单里的名字：只进本机日志，不进回报。
            log::warn!(
                "visudo -cf failed (exit code {}): {}",
                o.code,
                o.stderr.trim()
            );
            false
        }
        Err(e) => {
            log::warn!("cannot run visudo: {e:#}");
            false
        }
    };
    if !passed {
        let _ = safefs::remove_at(&dir, SUDOERS_CHECK);
        match out {
            Ok(o) => bail!(
                "visudo check failed (exit code {}); not installed, keeping the old file",
                o.code
            ),
            Err(e) => bail!("{e:#}; not installed, keeping the old file"),
        }
    }
    safefs::rename_at(&dir, SUDOERS_CHECK, SUDOERS_FILE)
}

/// 写 polkit 规则：空 → 删掉；否则 0644 写入（polkitd 监视目录，自己重新加载）。
fn apply_polkit(root: &Path, text: &str) -> Result<()> {
    let dir = match safefs::open_dir(root, Path::new(POLKIT_DIR), !text.is_empty()) {
        Ok(d) => d,
        Err(e) if text.is_empty() && is_not_found(&e) => return Ok(()),
        Err(e) => return Err(e).with_context(|| format!("open /{POLKIT_DIR}")),
    };
    if text.is_empty() {
        safefs::remove_at(&dir, POLKIT_FILE)
    } else {
        safefs::write_at(&dir, POLKIT_FILE, text.as_bytes(), 0o644).map(|_| ())
    }
}

/// 本机管理员组按开关设定成员（与现有成员不同时才 `gpasswd -M`）；开关关着时把本机用户移出 `sudo` 组；访客
/// 在 `sudo` 组里一律移出。返回问题列表（不带名字）。
fn apply_groups(env: &Env, root: &Path, local_admin: bool) -> Vec<String> {
    let mut problems = Vec::new();
    let read = |name: &str| -> Result<String> {
        let etc = safefs::open_dir(root, Path::new("etc"), false)?;
        let bytes =
            safefs::read_at(&etc, name)?.with_context(|| format!("/etc/{name} does not exist"))?;
        String::from_utf8(bytes).with_context(|| format!("/etc/{name} is not UTF-8"))
    };
    let (passwd, group) = match (read("passwd"), read("group")) {
        (Ok(p), Ok(g)) => (p, g),
        (Err(e), _) | (_, Err(e)) => {
            problems.push(format!("failed to read users and groups: {e:#}"));
            return problems;
        }
    };
    let humans = local_humans(&passwd);

    let want: Vec<String> = if local_admin {
        humans.clone()
    } else {
        Vec::new()
    };
    match group_members(&group, LOCAL_ADMIN_GROUP) {
        None => problems.push(format!("no {LOCAL_ADMIN_GROUP} group (image too old?)")),
        Some(cur) => {
            let same = cur.iter().collect::<BTreeSet<_>>() == want.iter().collect::<BTreeSet<_>>();
            if !same {
                let list = want.join(",");
                let cmd = Cmd::new("gpasswd", &["-M", &list, LOCAL_ADMIN_GROUP]);
                if let Err(e) = run_ok_redacted(env.runner, cmd) {
                    problems.push(format!(
                        "failed to set the members of {LOCAL_ADMIN_GROUP}: {e:#}"
                    ));
                }
            }
        }
    }

    let mut failures = 0;
    for (g, drop) in group_removals(&group, &humans, local_admin) {
        for m in drop {
            if run_ok_redacted(env.runner, Cmd::new("gpasswd", &["-d", &m, g])).is_err() {
                failures += 1;
            }
        }
    }
    if failures > 0 {
        problems.push(format!(
            "{failures} member(s) could not be removed from the administrator group"
        ));
    }
    problems
}

/// 每个管理员组里要移出的成员（组不存在的跳过）：
/// - `sudo`、`admin`：`root` 永远留着；开关关着时其余全部移出；开着时移出访客与不在 `humans` 里的。
/// - `adm`、`lpadmin`：访客一律移出；开关关着时再移出 `humans` 里的（系统账号留着）。
fn group_removals(
    group: &str,
    humans: &[String],
    local_admin: bool,
) -> Vec<(&'static str, Vec<String>)> {
    let mut out = Vec::new();
    for &g in ADMIN_GROUPS {
        let Some(members) = group_members(group, g) else {
            continue;
        };
        let drop: Vec<String> = members
            .into_iter()
            .filter(|m| m != "root" && (!local_admin || m == GUEST || !humans.contains(m)))
            .collect();
        out.push((g, drop));
    }
    for &g in EXTRA_ADMIN_GROUPS {
        let Some(members) = group_members(group, g) else {
            continue;
        };
        let drop: Vec<String> = members
            .into_iter()
            .filter(|m| m == GUEST || (!local_admin && humans.contains(m)))
            .collect();
        out.push((g, drop));
    }
    out
}

