    /// polkit 规则里 `return ` 与 `;` 之间的 JSON 列表。
    fn polkit_list(text: &str) -> Vec<String> {
        let start = text.find("return ").unwrap() + "return ".len();
        let end = start + text[start..].find(';').unwrap();
        serde_json::from_str(&text[start..end]).unwrap()
    }

