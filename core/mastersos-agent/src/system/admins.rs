//! 管理员（Ruling 6）：学校名单 `admin_users` 里的 SSO 账号在每台机器上都是管理员，本机用户是不是管理员由分组的
//! `local_users_admin` 决定。
//!
//! - sudoers：`/etc/sudoers.d/mastersos-admins`（0440）。先写成同目录的 `.mastersos-admins.check`（名字带点，sudo 的
//!   `@includedir` 不读它），`visudo -cf` 通过才 `renameat` 换上；不通过就删掉临时文件、保留旧文件、回报失败——
//!   坏的渲染不会让整台机器的 `sudo` 失效（Review Focus 5）。代价（复审 F8，有意保留）：检查不过时**旧**名单
//!   还在，刚从名单删掉的人在下一次渲染通过之前仍能 sudo（polkit 那边已经更新了）；渲染的输入受
//!   [`checks::admin_user`] 约束，visudo 拒收几乎不会发生，而反方向（换上坏文件）会让整机的 sudo 失效。
//! - polkit：`/etc/polkit-1/rules.d/49-mastersos-admins.rules`（0644），`addAdminRule` 返回名单。polkitd 把
//!   `/etc/polkit-1/rules.d` 与 `/usr/share/polkit-1/rules.d` 合起来按文件名排序，管理员规则用第一个返回非空列表的。
//!   Ubuntu 让 `sudo`、`admin` 组当 polkit 管理员的是 `/usr/share/polkit-1/rules.d/49-ubuntu-admin.rules`
//!   （`50-default.rules` 返回的是 `unix-user:0`）；我们的文件名排在它前面（测试 `polkit_file_sorts_before_ubuntu_admin`），
//!   写了它之后这两个组不再是 polkit 的管理员。名单与开关都空时删掉它，退回发行版的默认值（这时两个组也空了，见下）。
//! - 本机管理员组 `mastersos-localadmin`（镜像的 sysusers 建）：`local_users_admin = true` 时成员是全部本机用户，
//!   sudoers 与 polkit 都认这个组；`false` 时清空。
//! - 发行版的管理员组 `sudo`、`admin`（`/etc/sudoers` 里的 `%sudo`、`%admin`，复审 F1）：受管机器上合法的管理员只经
//!   我们的 sudoers 与 polkit 文件。`false` 时除 `root` 外的成员全部移出（有人在 GNOME 设置里勾了「管理员」、
//!   或某个 SSO 管理员被 `usermod -aG sudo` 过，从名单删掉之后都不能留着 root；受管机器上没有本机后门管理员，
//!   4a Ruling 18）；`true` 时移出访客与一切不是本机用户的成员（SSO 账号该写进 `admin_users`，系统账号不该在里面）。
//!   没有 `admin` 组时什么都不做。`false` 时本机用户还移出 `adm`、`lpadmin`（GNOME 的「管理员」账号类型另外给的：
//!   读系统日志、免口令管打印机，复审 F4）；系统账号（如 `syslog`）留着。
//! - 访客（`guest`）不是本机用户（[`local_humans`] 不含它），也进不了名单（名字没有 `@`）；它若被谁加进了上面
//!   任何一个组，不论开关都移出。
//! - 名字一律转小写：`pam-check` 比较不区分大小写，sudoers 与 polkit 区分（authd 给的用户名是小写）。
//!   不合 [`checks::admin_user`] 的跳过、回报失败，其余照常（Global Constraints）。
//! - The IT maintenance account `itadmin` (phase B design §10.4) is always an administrator: when the settings keep it
//!   (a valid `it_account`) and the account on the machine is the one the `it_account` step created
//!   ([`super::it_account::owned`]), sudoers gets `itadmin ALL=(ALL:ALL) ALL` and polkit `unix-user:itadmin`, whatever
//!   `local_users_admin` says. Before the first bundle ([`run_seed`]) only those two files are written from the seed's
//!   `it_account` (no administrators from a list, no local administrators); no group membership is touched.
//! - 回报里没有用户标识：跳过的只写个数；`visudo`、`gpasswd` 的 stderr 可能带名字，只写退出码。

