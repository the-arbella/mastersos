//! The one login-screen banner (GDM dconf keyfile `90-mastersos-lock`).
//!
//! Two writers share it: the `lock` step (lock message, set while the bundle says the computer is locked) and the
//! background status job (offline / no settings / no browser, see [`crate::status`]). Only one line of text is ever
//! shown, by priority: lock message > network > settings > Chrome; nothing when all is well. [`compose`] picks the text,
//! [`sync`] writes or removes the file, [`refresh_from_policy`] does both and runs `dconf update` when the file changed;
//! [`lock_text`] is the one place that turns the login policy into the lock message.
//! The file keeps the name the lock-only banner had (`90-mastersos-lock`): an agent from before the status banner,
//! after a rollback, then still removes it on unlock and overwrites it when locked, so no stale status line is left.
//! The status job's `dconf update` compiles every dconf database and may land in the middle of an apply that is still
//! writing other dconf fragments; that apply's own `dconf update` afterwards compiles the finished set again.

use std::path::Path;
use std::sync::Mutex;

use anyhow::{Context, Result};

use super::login::{self, LoginPolicy, DENY_LOCKED};
use super::SysPaths;
use crate::apply::is_not_found;
use crate::runner::{run_ok, Cmd, Runner};
use crate::safefs;
use crate::status::{read_status, Status};

/// GDM's dconf keyfile directory (relative to the system root; profile `gdm` is `user-db:user` + `system-db:gdm` + greeter defaults).
pub const GDM_DCONF_DIR: &str = "etc/dconf/db/gdm.d";
/// The banner fragment we write (the lock-only banner's name, kept for rollbacks: see the module doc).
pub const BANNER_FILE: &str = "90-mastersos-lock";

const HEADER: &str = "# Generated by mastersos-agent: login screen banner; do not edit.\n";

/// Serialises the status job and the lock step, which run in the same process.
static BANNER: Mutex<()> = Mutex::new(());

/// The banner text: the lock message wins; else the first problem in `status` as `"<sentence>\n<detail>"`
/// (one line without detail); `None` when there is nothing to say.
pub fn compose(lock_message: Option<&str>, status: Option<&Status>) -> Option<String> {
    if let Some(m) = lock_message {
        return Some(m.to_string());
    }
    let (sentence, detail) = status?.headline()?;
    Some(match detail {
        Some(d) if !d.is_empty() => format!("{sentence}\n{d}"),
        _ => sentence.to_string(),
    })
}

/// Writes the fragment for `text` (0644: the greeter reads the compiled database as `gdm-greeter*`; the fragment holds
/// no secret) or removes it for `None`. Returns whether anything changed.
pub fn sync(root: &Path, text: Option<&str>) -> Result<bool> {
    match text {
        Some(t) => {
            let dir = safefs::open_dir(root, Path::new(GDM_DCONF_DIR), true)?;
            safefs::write_at(
                &dir,
                BANNER_FILE,
                render_gdm_banner(Some(t)).as_bytes(),
                0o644,
            )
            .with_context(|| format!("writing /{GDM_DCONF_DIR}/{BANNER_FILE}"))
        }
        None => {
            let dir = match safefs::open_dir(root, Path::new(GDM_DCONF_DIR), false) {
                Ok(d) => d,
                Err(e) if is_not_found(&e) => return Ok(false),
                Err(e) => return Err(e),
            };
            remove_if_present(&dir, BANNER_FILE)
        }
    }
}

fn remove_if_present(dir: &std::os::fd::OwnedFd, name: &str) -> Result<bool> {
    if safefs::read_at(dir, name)?.is_none() {
        return Ok(false);
    }
    safefs::remove_at(dir, name).with_context(|| format!("removing /{GDM_DCONF_DIR}/{name}"))?;
    Ok(true)
}

/// Composes from `lock_message` and the saved status, then syncs the file. No `dconf update`: the caller owns that
/// (the lock step batches it with the other dconf writers). Returns whether the file changed.
pub fn update(paths: &SysPaths, lock_message: Option<&str>) -> Result<bool> {
    let _g = lock();
    compose_and_sync(paths, lock_message)
}

/// [`update`] plus `dconf update` when the file changed (tests only; production goes through [`refresh_from_policy`]).
#[cfg(test)]
pub fn refresh(paths: &SysPaths, runner: &dyn Runner, lock_message: Option<&str>) -> Result<bool> {
    let _g = lock();
    let changed = compose_and_sync(paths, lock_message)?;
    if changed {
        dconf_update(runner)?;
    }
    Ok(changed)
}

/// Composes and syncs (as [`update`]) with the lock text read from the login policy on disk ([`login::effective_policy`], as `pam-check`
/// reads it) while holding the banner lock: the lock step writes the policy before its banner update, so reading it
/// under the lock cannot put the status line over a lock message the lock step is about to write. Used by the
/// status job and `apply-local`. Runs `dconf update` when the file changed.
pub fn refresh_from_policy(paths: &SysPaths, runner: &dyn Runner) -> Result<bool> {
    let _g = lock();
    let policy = login::policy_at(paths);
    let changed = compose_and_sync(paths, policy.as_ref().and_then(lock_text))?;
    if changed {
        dconf_update(runner)?;
    }
    Ok(changed)
}

/// `dconf update` (compiles every dconf database, the GDM one included).
pub fn dconf_update(runner: &dyn Runner) -> Result<()> {
    run_ok(runner, Cmd::new("dconf", &["update"])).context("dconf update")?;
    Ok(())
}

/// The lock message the banner shows for `policy`: `None` unless it is locked; IT's message, or the `pam-check`
/// denial reason when the message is empty. The lock step and the status job both use it, so they never disagree
/// (two different texts would make them rewrite the banner, and run `dconf update`, every round).
pub fn lock_text(policy: &LoginPolicy) -> Option<&str> {
    if !policy.locked {
        return None;
    }
    Some(match policy.lock_message.as_deref() {
        Some(m) if !m.trim().is_empty() => m,
        _ => DENY_LOCKED,
    })
}

fn lock() -> std::sync::MutexGuard<'static, ()> {
    BANNER.lock().unwrap_or_else(|e| e.into_inner())
}

/// Callers hold [`BANNER`].
fn compose_and_sync(paths: &SysPaths, lock_message: Option<&str>) -> Result<bool> {
    let status = read_status(paths);
    sync(
        &paths.root,
        compose(lock_message, status.as_ref()).as_deref(),
    )
}

/// The login-screen banner's dconf keyfile for a message; an empty string for `None` (the caller removes the file).
pub fn render_gdm_banner(message: Option<&str>) -> String {
    match message {
        None => String::new(),
        Some(m) => format!(
            "{HEADER}[org/gnome/login-screen]\n\
             banner-message-enable=true\n\
             banner-message-text={}\n",
            gv_text(m)
        ),
    }
}

/// A string in GVariant text form. dconf takes the keyfile value **as is** (no GKeyFile unescaping) and parses it as
/// GVariant text, so control characters must be GVariant escapes, never a real newline (that would end the line):
/// single-quoted, `\` and `'` prefixed with `\`, newline / carriage return / tab as `\n` `\r` `\t`, other control
/// characters as `\uXXXX`.
pub(super) fn gv_text(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('\'');
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '\'' => o.push_str("\\'"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if c.is_control() => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('\'');
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    use super::super::tests::{paths, tmp_root};
    use crate::runner::FakeRunner;
    use crate::status::{write_status, Browser, Net, Settings};

    const NET: &str = "No network. Choose a Wi-Fi network in the top-right menu, or plug in a network cable or a phone with USB tethering.";
    const SET: &str = "Waiting for school settings.";
    const CHR: &str = "Installing the web browser. You can sign in; it will appear when ready.";

    fn st(n: Net, nd: Option<&str>, s: Settings, c: Browser) -> Status {
        Status::new(n, nd.map(str::to_string), s, None, c, None)
    }

    fn banner_text(root: &Path) -> Option<String> {
        std::fs::read_to_string(root.join(GDM_DCONF_DIR).join(BANNER_FILE)).ok()
    }

    #[test]
    fn lock_wins_over_status() {
        let s = st(
            Net::Disconnected,
            None,
            Settings::Waiting,
            Browser::Installing,
        );
        assert_eq!(
            compose(Some("Return to IT"), Some(&s)).as_deref(),
            Some("Return to IT")
        );
    }

    #[test]
    fn priority_network_then_settings_then_chrome() {
        let s = st(
            Net::Disconnected,
            Some("Not connected"),
            Settings::Waiting,
            Browser::Installing,
        );
        assert_eq!(
            compose(None, Some(&s)).unwrap(),
            format!("{NET}\nNot connected")
        );
        let s = st(Net::Ok, None, Settings::Waiting, Browser::Installing);
        assert_eq!(compose(None, Some(&s)).as_deref(), Some(SET));
        let s = st(Net::Ok, None, Settings::Ok, Browser::Installing);
        assert_eq!(compose(None, Some(&s)).as_deref(), Some(CHR));
    }

    #[test]
    fn all_ok_is_none() {
        let s = st(Net::Ok, None, Settings::Ok, Browser::Ok);
        assert_eq!(compose(None, Some(&s)), None);
        assert_eq!(compose(None, None), None);
    }

    #[test]
    fn exact_copy_lines() {
        let s = st(Net::WifiOff, None, Settings::Waiting, Browser::Installing);
        assert_eq!(compose(None, Some(&s)).as_deref(), Some(NET));
    }

    /// An agent from before the status banner only knows `90-mastersos-lock`: after a rollback it must find (and on
    /// unlock remove) the status banner under that name.
    #[test]
    fn banner_keeps_the_lock_only_file_name() {
        assert_eq!(BANNER_FILE, "90-mastersos-lock");
        let root = tmp_root();
        let dir = root.path().join(GDM_DCONF_DIR);
        assert!(sync(root.path(), Some("hello")).unwrap());
        let names: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .collect();
        assert_eq!(names, vec!["90-mastersos-lock".to_string()]);
        assert!(sync(root.path(), None).unwrap());
        assert!(!dir.join(BANNER_FILE).exists());
    }

    #[test]
    fn sync_unchanged_returns_false() {
        let root = tmp_root();
        assert!(!sync(root.path(), None).unwrap());
        assert!(sync(root.path(), Some("x")).unwrap());
        assert!(!sync(root.path(), Some("x")).unwrap());
        assert!(sync(root.path(), Some("y")).unwrap());
    }

    #[test]
    fn refresh_runs_dconf_update_only_on_change() {
        let root = tmp_root();
        let p = paths(root.path());
        write_status(
            &p,
            &st(
                Net::Disconnected,
                Some("Not connected"),
                Settings::Ok,
                Browser::Ok,
            ),
        )
        .unwrap();
        let r = FakeRunner::new();
        assert!(refresh(&p, &r, None).unwrap());
        assert!(!refresh(&p, &r, None).unwrap());
        let n = r.calls().iter().filter(|c| *c == "dconf update").count();
        assert_eq!(n, 1);
        assert!(banner_text(root.path()).unwrap().contains("No network"));
        // A lock message replaces it; then the status job running again leaves the lock message alone.
        assert!(refresh(&p, &r, Some("Locked")).unwrap());
        assert!(banner_text(root.path()).unwrap().contains("Locked"));
    }

    #[test]
    fn lock_text_falls_back_when_empty() {
        let mut p = crate::system::login::LoginPolicy {
            methods: vec![],
            allowed_domains: vec![],
            admin_users: vec![],
            locked: false,
            lock_message: Some("Return to IT".into()),
            from_bundle: true,
            kiosk_users: vec![],
            it_account: false,
            it_account_uid: None,
        };
        assert_eq!(lock_text(&p), None, "not locked");
        p.locked = true;
        assert_eq!(lock_text(&p), Some("Return to IT"));
        p.lock_message = Some("  ".into());
        assert_eq!(lock_text(&p), Some(DENY_LOCKED));
        p.lock_message = None;
        assert_eq!(lock_text(&p), Some(DENY_LOCKED));
    }

    #[test]
    fn banner_escapes_quotes_and_newlines() {
        assert_eq!(render_gdm_banner(None), "");
        let text = render_gdm_banner(Some("It's \\ IT\nline 2\tx\u{7}"));
        assert!(text.contains("[org/gnome/login-screen]\n"), "{text}");
        assert!(text.contains("\nbanner-message-enable=true\n"), "{text}");
        assert!(
            text.contains("\nbanner-message-text='It\\'s \\\\ IT\\nline 2\\tx\\u0007'\n"),
            "{text}"
        );
        // No real newline in the value: after the header comment every line is a group or key=value.
        for l in text.lines().skip(1) {
            assert!(l.starts_with('[') || l.contains('='), "{l:?}");
        }
    }

    /// Read back with GLib (Ruling 15): dconf takes the raw value with `g_key_file_get_value` and parses it with `g_variant_parse`.
    #[cfg(target_os = "linux")]
    #[test]
    fn banner_roundtrips_through_glib() {
        for m in [
            "It's \\ IT\nline 2",
            "本机已挂失，请交回 IT 办公室 / เครื่องนี้ถูกล็อก",
            " lead 'q' \"dq\" \r\t\u{1b}end ",
            "",
        ] {
            let text = render_gdm_banner(Some(m));
            let kf = glib::KeyFile::new();
            kf.load_from_data(&text, glib::KeyFileFlags::NONE).unwrap();
            let raw = kf
                .value("org/gnome/login-screen", "banner-message-text")
                .unwrap();
            let v = glib::Variant::parse(None, raw.as_str()).unwrap();
            assert_eq!(v.str(), Some(m), "{m:?}");
            let en = kf
                .value("org/gnome/login-screen", "banner-message-enable")
                .unwrap();
            assert_eq!(
                glib::Variant::parse(None, en.as_str())
                    .unwrap()
                    .get::<bool>(),
                Some(true)
            );
        }
    }
}
