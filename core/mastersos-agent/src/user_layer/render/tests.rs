#[test]
fn locks_follow_capabilities() {
    let caps = |cs: &[Capability]| cs.iter().copied().collect::<Caps>();
    assert_eq!(desktop::session_locks(&Caps::new()), desktop::LOCKED_KEYS);
    assert!(desktop::session_locks(&caps(&ALL_CAPS)).is_empty());
    let t = desktop::session_locks(&caps(&[Capability::Terminal]));
    assert!(!t.contains(&"/org/gnome/desktop/lockdown/disable-command-line"));
    assert!(!t.contains(&"/org/gnome/settings-daemon/plugins/media-keys/terminal"));
    assert!(t.contains(&"/org/gnome/shell/favorite-apps"));
    assert!(t.contains(&"/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings"));
    let s = desktop::session_locks(&caps(&[Capability::Settings]));
    assert!(!s.contains(&"/org/gnome/desktop/lockdown/user-administration-disabled"));
    assert_eq!(s.len(), desktop::LOCKED_KEYS.len() - 1);
    let e = desktop::session_locks(&caps(&[Capability::Extensions]));
    assert_eq!(e.len(), desktop::LOCKED_KEYS.len() - 4);
    assert!(!e.iter().any(|k| k.contains("extension")));
    // every capability but one: the keys of no capability stay locked
    let most = caps(&ALL_CAPS[..5]);
    assert_eq!(
        desktop::session_locks(&most),
        [
            "/org/gnome/shell/favorite-apps",
            "/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings"
        ]
    );
}

/// The text of a locked session is the one the desktop step wrote before the user layer, byte for byte.
#[test]
fn learning_dconf_text_is_unchanged() {
    let session = SessionDconf {
        locks: desktop::LOCKED_KEYS,
        dock_files: false,
        dock_apps: true,
    };
    let (k, locks) = desktop::render_session_dconf(
        &session,
        &["w.desktop".into()],
        &[],
        &["d.desktop".into()],
        &["org.example.F".into()],
    );
    assert_eq!(
        k,
        format!(
            "{HEADER}\n[org/gnome/shell]\nfavorite-apps=['google-chrome.desktop', 'w.desktop', 'd.desktop', \
             'org.example.F.desktop']\ndisabled-extensions=@as []\ndisable-user-extensions=true\n\
             allow-extension-installation=false\nenabled-extensions=['ubuntu-appindicators@ubuntu.com', \
             'mastersos-managed@mastersos.org']\n\n[org/gnome/desktop/screensaver]\nlock-enabled=true\n\n\
             [org/gnome/desktop/lockdown]\ndisable-command-line=true\nuser-administration-disabled=true\n\n\
             [org/gnome/settings-daemon/plugins/media-keys]\nterminal=['']\ncustom-keybindings=@as []\n"
        )
    );
    assert_eq!(
        locks,
        format!("{HEADER}{}\n", desktop::LOCKED_KEYS.join("\n"))
    );
    let full = SessionDconf {
        locks: &[],
        dock_files: true,
        dock_apps: true,
    };
    let (k, locks) = desktop::render_session_dconf(&full, &[], &[], &[], &[]);
    assert_eq!(
        k,
        format!(
            "{HEADER}\n[org/gnome/shell]\nfavorite-apps=['google-chrome.desktop', 'org.gnome.Nautilus.desktop']\n\n\
             [org/gnome/desktop/screensaver]\nlock-enabled=true\n"
        )
    );
    assert!(locks.is_empty());
}
