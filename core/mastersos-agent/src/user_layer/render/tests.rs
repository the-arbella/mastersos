/// A system root with a few visible apps and the exec-block stub and targets.
fn root() -> tempfile::TempDir {
    let root = tmp_root();
    put_image(root.path());
    let apps = root.path().join("usr/share/applications");
    fs::create_dir_all(&apps).unwrap();
    for name in [
        "google-chrome.desktop",
        "org.gnome.Nautilus.desktop",
        "org.gnome.Terminal.desktop",
        "org.gnome.Settings.desktop",
        "org.example.Other.desktop",
    ] {
        fs::write(
            apps.join(name),
            format!("[Desktop Entry]\nType=Application\nName={name}\nExec=x\n"),
        )
        .unwrap();
    }
    root
}

/// Runs `step` with the settings `m` on the Device of Group `default`.
fn run_step_with(
    step: Step,
    root: &Path,
    m: &Manifest,
    r: &dyn crate::runner::Runner,
    sys: &mut SysState,
) -> Vec<ItemResult> {
    let ident = test_ident();
    let sel = select(m, &ident, None);
    let bundle = tempfile::tempdir().unwrap();
    let flag = AtomicBool::new(false);
    let ctx = ApplyContext {
        seed: &test_seed(),
        school: &m.school,
        group: sel.group,
        config: &sel.config,
        lock: None,
        bundle_dir: bundle.path(),
        phase: Phase::Full,
        superseded: &flag,
        quiet: &AtomicBool::new(false),
        device: None,
        ident: &ident,
        manifest: Some(m),
    };
    let p = paths(root);
    let mut env = Env {
        paths: &p,
        runner: r,
        sys,
    };
    (step.run)(&ctx, &mut env)
}

fn render(root: &Path, m: &Manifest) -> (Vec<ItemResult>, CompileRunner) {
    let r = CompileRunner::default();
    let out = run_step_with(step(), root, m, &r, &mut SysState::default());
    (out, r)
}

/// A [`FakeRunner`] whose successful `dconf compile <out> <dir>` writes a stand-in database to `<out>` (0644, as
/// `dconf compile` leaves it under umask 022).
#[derive(Default)]
pub(crate) struct CompileRunner(pub(crate) FakeRunner);

impl std::ops::Deref for CompileRunner {
    type Target = FakeRunner;
    fn deref(&self) -> &FakeRunner {
        &self.0
    }
}

impl crate::runner::Runner for CompileRunner {
    fn run(&self, cmd: &crate::runner::Cmd) -> anyhow::Result<crate::runner::Output> {
        let out = self.0.run(cmd)?;
        fake_compile(cmd, &out)?;
        Ok(out)
    }
}

/// What a successful `dconf compile <out> <dir>` leaves: a stand-in database at `<out>`.
fn fake_compile(cmd: &crate::runner::Cmd, out: &crate::runner::Output) -> anyhow::Result<()> {
    if out.code == 0 && cmd.program == "dconf" && cmd.args.first().is_some_and(|a| a == "compile") {
        let db = &cmd.args[1];
        fs::write(db, format!("db compiled from {}", cmd.args[2]))?;
        fs::set_permissions(db, fs::Permissions::from_mode(0o644))?;
    }
    Ok(())
}

/// [`CompileRunner`] that also simulates the exec-block bind mounts ([`MountSim`]).
struct LiveRunner(MountSim);

impl crate::runner::Runner for LiveRunner {
    fn run(&self, cmd: &crate::runner::Cmd) -> anyhow::Result<crate::runner::Output> {
        let out = self.0.run(cmd)?;
        fake_compile(cmd, &out)?;
        Ok(out)
    }
}

fn var(root: &Path) -> PathBuf {
    root.join("var/lib/mastersos-system/user-layer")
}

fn public(root: &Path) -> PathBuf {
    root.join("var/lib/mastersos-public/user-layer")
}

fn db(root: &Path) -> PathBuf {
    root.join(DCONF_DB_DIR)
}

fn staging(root: &Path) -> PathBuf {
    root.join(POLICIES_DIR).join(STAGING_SUB)
}

fn names(dir: &Path) -> Vec<String> {
    let mut v: Vec<String> = match fs::read_dir(dir) {
        Ok(rd) => rd
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .collect(),
        Err(_) => vec![],
    };
    v.sort();
    v
}

fn read(p: PathBuf) -> String {
    fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

fn keyfile(root: &Path, d: &str) -> String {
    read(
        var(root)
            .join(d)
            .join(DCONF_KEYFILE_SUB)
            .join("50-mastersos"),
    )
}

fn lockfile(root: &Path, d: &str) -> Option<String> {
    fs::read_to_string(
        var(root)
            .join(d)
            .join(DCONF_KEYFILE_SUB)
            .join("locks/50-mastersos"),
    )
    .ok()
}

fn compiles(r: &FakeRunner) -> Vec<String> {
    r.calls()
        .into_iter()
        .filter(|c| c.starts_with("dconf compile"))
        .collect()
}

/// Every file of this layer's first layout in `/etc/dconf/db` (`mastersos-<config dir>` and its `.d`).
fn old_layout(root: &Path) -> Vec<String> {
    names(&db(root))
        .into_iter()
        .filter(|n| {
            n.strip_prefix("mastersos-")
                .map(|r| r.strip_suffix(".d").unwrap_or(r))
                .is_some_and(crate::user_layer::is_config_dir)
        })
        .collect()
}

fn apps_of(root: &Path, d: &str) -> Vec<String> {
    names(&public(root).join(d).join("xdg/applications"))
}

fn services_of(root: &Path, d: &str) -> Vec<String> {
    names(&public(root).join(d).join("xdg/dbus-1/services"))
}

fn is_hidden(root: &Path, d: &str, app: &str) -> bool {
    fs::read_to_string(public(root).join(d).join("xdg/applications").join(app))
        .is_ok_and(|t| t.contains("Hidden=true"))
}

fn ok_item<'a>(out: &'a [ItemResult], name: &str) -> &'a ItemResult {
    let i = out
        .iter()
        .find(|r| r.item == name)
        .unwrap_or_else(|| panic!("no item {name}: {out:?}"));
    assert!(i.ok, "{i:?}");
    i
}

fn dconf_updates(r: &FakeRunner) -> usize {
    r.calls().iter().filter(|c| *c == "dconf update").count()
}

#[test]
fn renders_every_reachable_config_and_neutral() {
    let root = root();
    let (out, r) = render(root.path(), &v3());
    let (teacher, primary) = (config_dir_name("teacher"), config_dir_name("primary"));
    ok_item(&out, ITEM);
    ok_item(&out, "user-layer:config:teacher");
    ok_item(&out, "user-layer:config:primary");
    let mut want = vec![teacher.clone(), primary.clone(), NEUTRAL_DIR.to_string()];
    want.sort();
    let mut with_index = want.clone();
    with_index.push(INDEX_FILE.into());
    with_index.sort();
    assert_eq!(names(&var(root.path())), with_index);
    assert_eq!(names(&public(root.path())), want);
    for d in &want {
        assert!(var(root.path()).join(d).join(CHROME_FILE).is_file(), "{d}");
        // neutral's staging copy was renamed into managed/ by the switch at the end of the step
        assert_eq!(
            staging(root.path()).join(format!("{d}.json")).is_file(),
            d != NEUTRAL_DIR,
            "{d}"
        );
        assert!(var(root.path())
            .join(d)
            .join(DCONF_KEYFILE_SUB)
            .join("50-mastersos")
            .is_file());
        assert!(public(root.path())
            .join(d)
            .join("login-scripts/index.json")
            .is_file());
    }
    // the staging copies sit beside managed/, never in it
    assert_eq!(
        names(&root.path().join(POLICIES_DIR).join("managed")),
        ["mastersos.json"]
    );
    let index = read_index(&root.path().join("var/lib/mastersos-system")).unwrap();
    assert_eq!(index.group, "default");
    assert_eq!(index.rules.fallback, "primary");
    assert_eq!(index.rules.rules.len(), 3);
    assert_eq!(
        index.configs.keys().cloned().collect::<Vec<_>>(),
        ["primary", "teacher"]
    );
    assert_eq!(index.configs["teacher"].dir, teacher);
    assert_eq!(index.configs["teacher"].home, HomeMode::Keep);
    assert_eq!(index.configs["primary"].dir, primary);
    assert_eq!(index.configs["primary"].caps, Caps::new());
    assert_eq!(index.neutral.dir, NEUTRAL_DIR);
    // the user configs' Chrome policies: primary keeps the defaults' block list, teacher drops it
    let chrome = |d: &str| read(var(root.path()).join(d).join(CHROME_FILE));
    assert!(chrome(&primary).contains("tiktok.com"));
    assert!(!chrome(&teacher).contains("tiktok.com"));
    assert!(chrome(&teacher).contains("\"BrowserSignin\": 0"));
    assert_eq!(
        chrome(&primary),
        read(staging(root.path()).join(format!("{primary}.json")))
    );
    // the defaults' web app in both user configs, not in neutral
    let launcher = desktop::webapp_file("https://classroom.google.com");
    assert!(apps_of(root.path(), &primary).contains(&launcher));
    assert!(apps_of(root.path(), &teacher).contains(&launcher));
    assert!(!apps_of(root.path(), NEUTRAL_DIR).contains(&launcher));
    assert!(keyfile(root.path(), &primary).contains(&launcher));
    // each config compiled root-only into its own var dir; nothing per config in /etc/dconf/db, no dconf update
    // (only the device database's, when the desktop step asks for it)
    let mut want_compiles: Vec<String> = want
        .iter()
        .map(|d| {
            let v = var(root.path()).join(d);
            format!(
                "dconf compile {} {}",
                v.join(DCONF_DB_TMP).display(),
                v.join(DCONF_KEYFILE_SUB).display()
            )
        })
        .collect();
    want_compiles.sort();
    let mut got = compiles(&r);
    got.sort();
    assert_eq!(got, want_compiles);
    assert_eq!(dconf_updates(&r), 0, "{:?}", r.calls());
    assert_eq!(names(&db(root.path())), [SESSION_DB]);
    assert_eq!(
        compiled_db(
            root.path(),
            &root.path().join("var/lib/mastersos-system"),
            &primary
        ),
        var(root.path()).join(&primary).join(DCONF_DB_FILE)
    );
    // the legacy session mode stays learning
    assert_eq!(
        read(root.path().join("var/lib/mastersos-public/session-mode")),
        "learning\n"
    );
    // nobody is signed in: neutral is switched in, nothing lifted, nothing to report about the session
    assert_eq!(
        session_link(root.path()).as_deref(),
        Some("user-layer/neutral")
    );
    assert_eq!(
        read(
            root.path()
                .join(POLICIES_DIR)
                .join("managed/mastersos.json")
        ),
        read(var(root.path()).join(NEUTRAL_DIR).join(CHROME_FILE))
    );
    assert_eq!(lifted(root.path()), Caps::new());
    assert!(out.iter().all(|i| i.item != ACTIVE_ITEM), "{out:?}");
}

